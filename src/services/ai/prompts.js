function buildCoachingQuestionPrompt(stats) {
  return [
    'Ты коуч по продуктивности для предпринимателя.',
    'Сгенерируй 1 короткий вопрос для вечерней рефлексии на русском языке.',
    'Ограничения: до 140 символов, без воды, без эмодзи, только один вопросительный знак.',
    'Фокус: стратегический приоритет и следующий конкретный шаг.',
    `Данные дня: total=${stats.total}, done=${stats.done}, skipped=${stats.skipped}, pending=${stats.pending}, sfi=${stats.sfi}, fireDone=${stats.fireDone}.`,
    'Верни только текст вопроса без пояснений.',
  ].join('\n');
}

function buildNoStrategyPlanPrompt({ goal, area, bandwidth }) {
  return [
    'Ты продуктовый ассистент по фокусу.',
    'Сформируй короткий план для пользователя без стратегии.',
    'Верни строго 3-5 шагов на русском языке.',
    'Каждый шаг: одна строка, конкретное действие, до 90 символов.',
    'Никаких вводных фраз, только список шагов.',
    `Цель: ${goal}.`,
    `Область фокуса: ${area}.`,
    `Доступный ресурс в день: ${bandwidth}.`,
    'Шаги должны быть выполнимы в ближайшие 1-2 дня.',
  ].join('\n');
}

module.exports = { buildCoachingQuestionPrompt, buildNoStrategyPlanPrompt };
